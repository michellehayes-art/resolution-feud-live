// Helper to shuffle questions so every game has a fresh order!
export function shuffleQuestions(questions: FeudQuestion[]): FeudQuestion[] {
  const arr = [...questions];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  // Deep clone answers and reset isRevealed state
  return arr.map((q, idx) => ({
    ...q,
    answers: q.answers.map((a) => ({ ...a, isRevealed: false, revealedBy: undefined })),
  }));
}

